/**
 * Слова с вариантами написания: «д(е/и)ревья» — первый вариант в скобках верный.
 * Пустой вариант допустим: «со(л/)нце».
 */
function spellVariants(pattern) {
  const parts = [];
  const re = /\(([^)]*)\)/g;
  let last = 0, m;
  while ((m = re.exec(pattern))) {
    parts.push(pattern.slice(last, m.index));
    parts.push(m[1].split('/'));
    last = re.lastIndex;
  }
  parts.push(pattern.slice(last));
  const build = choice => parts.map((p, i) => (typeof p === 'string' ? p : p[choice[i] || 0])).join('');
  const right = build({});
  const wrong = new Set();
  parts.forEach((p, i) => {
    if (typeof p !== 'string') for (let k = 1; k < p.length; k++) wrong.add(build({ [i]: k }));
  });
  // комбинированные ошибки, если пропусков несколько
  const gaps = parts.map((p, i) => (typeof p === 'string' ? -1 : i)).filter(i => i >= 0);
  if (gaps.length > 1) wrong.add(build(Object.fromEntries(gaps.map(i => [i, 1]))));
  wrong.delete(right);
  return { right, wrong: [...wrong] };
}

DB.gen('spell', ({ words }) => {
  const { right, wrong } = spellVariants(R.pick(words));
  return { q: 'Выберите правильное написание:', a: right, w: wrong };
});

// ударение: заглавная буква — ударная гласная
const VOWELS = 'аеёиоуыэюя';
DB.gen('stress', ({ words }) => {
  const word = R.pick(words);
  const lower = word.toLowerCase();
  const variants = [];
  for (let i = 0; i < lower.length; i++)
    if (VOWELS.includes(lower[i])) variants.push(lower.slice(0, i) + lower[i].toUpperCase() + lower.slice(i + 1));
  return { q: 'В каком варианте ударение поставлено верно? (ударная гласная — заглавная)', a: word, w: variants.filter(v => v !== word) };
});

DB.gen('classify', ({ items, question, labels }) => {
  const line = R.pick(items);
  const [word, key] = line.split(':');
  return { q: question.replace('%', word), a: labels[key] || key, w: R.others(Object.values(labels), labels[key] || key) };
});

const SIMPLE_WORDS = ['мама', 'машина', 'дом', 'карандаш', 'молоко', 'кот', 'собака', 'яблоко', 'ученик', 'школа', 'тетрадь', 'лиса', 'огород', 'воробей', 'стол', 'игрушка', 'книга', 'радуга', 'ромашка', 'крокодил', 'пенал', 'берёза', 'сорока', 'пароход', 'лес', 'капуста', 'самолёт', 'черепаха', 'малина', 'учитель'];
const countVowels = w => [...w].filter(c => VOWELS.includes(c)).length;

DB.gen('syllables', () => {
  const w = R.pick(SIMPLE_WORDS), n = countVowels(w);
  return { q: `Сколько слогов в слове «${w}»?`, a: n, w: [n + 1, Math.max(1, n - 1) === n ? n + 2 : n - 1, w.length] };
});

DB.gen('letters', () => {
  const w = R.pick(SIMPLE_WORDS);
  if (R.chance(0.5)) return { q: `Сколько букв в слове «${w}»?`, a: w.length, w: [w.length + 1, w.length - 1, countVowels(w)] };
  const v = countVowels(w);
  return { q: `Сколько гласных букв в слове «${w}»?`, a: v, w: [v + 1, w.length - v === v ? v + 2 : w.length - v, Math.max(0, v - 1) === v ? v + 3 : v - 1] };
});

