DB.gen('dates', ({ grades }) => {
  const pool = grades.flatMap(g => DATES[g]).map(line => { const i = line.indexOf(':'); return [line.slice(0, i), line.slice(i + 1)]; });
  const [year, event] = R.pick(pool);
  const label = y => (y.includes('до н. э.') ? y.replace(' до н. э.', ' г. до н. э.') : `${y} г.`);
  if (R.chance(0.55)) return { q: `В каком году: ${event}?`, a: label(year), w: R.others(pool.map(p => label(p[0])), label(year)) };
  return { q: `Какое событие произошло в ${label(year)}?`, a: event, w: R.others(pool.map(p => p[1]), event) };
});

