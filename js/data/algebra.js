const SUP = { '0': '⁰', '1': '¹', '2': '²', '3': '³', '4': '⁴', '5': '⁵', '6': '⁶', '7': '⁷', '8': '⁸', '9': '⁹', '-': '⁻' };
const sup = n => String(n).split('').map(c => SUP[c] || c).join('');
// k·x^n в красивом виде
const term = (k, v = 'x', n = 1, first = false) => {
  if (k === 0) return '';
  const abs = Math.abs(k);
  const coef = abs === 1 && n !== 0 ? '' : R.num(abs);
  const body = n === 0 ? R.num(abs) : `${coef}${v}${n === 1 ? '' : sup(n)}`;
  if (first) return (k < 0 ? '−' : '') + body;
  return (k < 0 ? ' − ' : ' + ') + body;
};
const poly = terms => {
  const parts = terms.filter(([k]) => k !== 0);
  if (!parts.length) return '0';
  return parts.map(([k, v, n], i) => term(k, v, n, i === 0)).join('');
};

