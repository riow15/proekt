/* ============ Генераторы: физика ============ */
const U = (x, unit) => `${R.num(x)} ${unit}`;
const units = (vals, unit) => vals.map(x => U(x, unit));

DB.gen('phSpeed', () => {
  const v = R.int(2, 30), t = R.int(2, 20), s = v * t;
  const k = R.int(0, 2);
  if (k === 0) return { q: `Тело прошло ${s} м за ${t} с. Найдите скорость.`, a: U(v, 'м/с'), w: units([s * t, v + t, v * 2], 'м/с') };
  if (k === 1) return { q: `Тело движется со скоростью ${v} м/с. Какой путь оно пройдёт за ${t} с?`, a: U(s, 'м'), w: units([v + t, s / 2, s + v], 'м') };
  const pairs = [[36, 10], [72, 20], [54, 15], [18, 5], [90, 25], [108, 30], [144, 40]];
  const [kmh, ms] = R.pick(pairs);
  return { q: `Переведите ${kmh} км/ч в м/с.`, a: U(ms, 'м/с'), w: units([kmh / 10, ms * 2, kmh * 3.6], 'м/с') };
});

DB.gen('phDensity', () => {
  const [name, rho] = R.pick([['вода', 1000], ['железо', 7800], ['алюминий', 2700], ['лёд', 900], ['медь', 8900], ['керосин', 800]]);
  const V = R.pick([0.001, 0.002, 0.005, 0.01, 0.02, 0.1, 0.5, 2]);
  const m = Math.round(rho * V * 1000) / 1000;
  return { q: `Найдите массу тела объёмом ${R.num(V)} м³ (вещество — ${name}, ρ = ${rho} кг/м³).`, a: U(m, 'кг'), w: units([m * 10, m / 10, m * 2], 'кг') };
});

DB.gen('phForce', () => {
  const k = R.int(0, 3);
  if (k === 0) { const m = R.int(1, 80); return { q: `Найдите силу тяжести, действующую на тело массой ${m} кг (g = 10 Н/кг).`, a: U(m * 10, 'Н'), w: units([m, m / 10, m * 100], 'Н') }; }
  if (k === 1) { const m = R.int(2, 20), a = R.int(1, 6); return { q: `Тело массой ${m} кг движется с ускорением ${a} м/с². Найдите равнодействующую силу.`, a: U(m * a, 'Н'), w: units([m + a, m / a > 1 ? Math.round(m / a) : m * a * 2, m * a * 10], 'Н') }; }
  if (k === 2) { const kk = R.int(1, 10) * 50, x = R.pick([0.02, 0.04, 0.05, 0.1]); return { q: `Жёсткость пружины ${kk} Н/м, удлинение ${R.num(x)} м. Найдите силу упругости.`, a: U(kk * x, 'Н'), w: units([kk / x, kk * x * 10, kk + x], 'Н') }; }
  const F = R.int(1, 20) * 100, S = R.pick([0.1, 0.2, 0.5, 2, 4]);
  return { q: `Сила ${F} Н действует на площадь ${R.num(S)} м². Найдите давление.`, a: U(F / S, 'Па'), w: units([F * S, F / S / 10, F / S * 2], 'Па') };
});

DB.gen('phWork', () => {
  const k = R.int(0, 2);
  if (k === 0) { const F = R.int(2, 50) * 10, s = R.int(2, 20); return { q: `Под действием силы ${F} Н тело переместилось на ${s} м вдоль силы. Найдите работу.`, a: U(F * s, 'Дж'), w: units([F / s, F + s, F * s * 10], 'Дж') }; }
  if (k === 1) { const A = R.int(2, 60) * 100, t = R.pick([2, 4, 5, 10, 20]); return { q: `Двигатель совершил работу ${A} Дж за ${t} с. Найдите мощность.`, a: U(A / t, 'Вт'), w: units([A * t, A / t / 10, A - t], 'Вт') }; }
  const m = R.int(1, 20), h = R.int(1, 20);
  return { q: `Найдите потенциальную энергию тела массой ${m} кг на высоте ${h} м (g = 10 Н/кг).`, a: U(m * h * 10, 'Дж'), w: units([m * h, (m * h * 10) / 2, m + h], 'Дж') };
});

DB.gen('phEnergy', () => {
  const k = R.int(0, 2);
  if (k === 0) { const m = R.int(1, 10) * 2, v = R.int(1, 10); return { q: `Найдите кинетическую энергию тела массой ${m} кг, движущегося со скоростью ${v} м/с.`, a: U((m * v * v) / 2, 'Дж'), w: units([m * v * v, (m * v) / 2, m * v], 'Дж') }; }
  if (k === 1) { const m = R.int(1, 10), v = R.int(1, 20); return { q: `Найдите импульс тела массой ${m} кг, движущегося со скоростью ${v} м/с.`, a: U(m * v, 'кг·м/с'), w: units([(m * v * v) / 2, m + v, m * v * 2], 'кг·м/с') }; }
  const t = R.int(1, 5);
  return { q: `Тело свободно падает без начальной скорости. Какую скорость оно наберёт за ${t} с? (g = 10 м/с²)`, a: U(10 * t, 'м/с'), w: units([5 * t * t, 10 * t * t, t], 'м/с') };
});

DB.gen('phHeat', () => {
  const m = R.pick([0.5, 1, 2, 3, 5]), dt = R.int(1, 8) * 10;
  const [name, c] = R.pick([['воды', 4200], ['алюминия', 920], ['меди', 400], ['железа', 460]]);
  const Q = c * m * dt;
  return { q: `Какое количество теплоты нужно для нагревания ${R.num(m)} кг ${name} на ${dt} °C? (c = ${c} Дж/(кг·°C))`, a: U(Q, 'Дж'), w: units([c * dt, c * m, Q * 10], 'Дж') };
});

DB.gen('phElectric', () => {
  const k = R.int(0, 3);
  if (k === 0) { const I = R.int(1, 10), Rr = R.int(2, 50); return { q: `Сопротивление проводника ${Rr} Ом, сила тока ${I} А. Найдите напряжение.`, a: U(I * Rr, 'В'), w: units([Rr / I, I + Rr, I * Rr * 2], 'В') }; }
  if (k === 1) { const I = R.int(1, 10), Rr = R.int(2, 50), Uu = I * Rr; return { q: `Напряжение ${Uu} В, сопротивление ${Rr} Ом. Найдите силу тока.`, a: U(I, 'А'), w: units([Uu * Rr, I * 2, I + 1], 'А') }; }
  if (k === 2) { const r = R.int(1, 10) * 2, n = R.int(2, 4); return { q: `${n} одинаковых резистора по ${r} Ом соединены последовательно. Найдите общее сопротивление.`, a: U(r * n, 'Ом'), w: units([r / n, r, r * n * 2], 'Ом') }; }
  const r = R.pick([2, 4, 6, 8, 12]), n = 2;
  return { q: `Два одинаковых резистора по ${r} Ом соединены параллельно. Найдите общее сопротивление.`, a: U(r / n, 'Ом'), w: units([r * n, r, r / 4], 'Ом') };
});

